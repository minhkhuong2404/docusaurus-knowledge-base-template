export function getRankForLevel(level: number): CosmicRank {
  for (let i = COSMIC_RANKS.length - 1; i >= 0; i--) {
    if (level >= COSMIC_RANKS[i].minLevel) {
      return COSMIC_RANKS[i];
    }
  }
  return COSMIC_RANKS[0];
}

/**
 * Level formula:
 * Total EXP required to REACH level L:
 * Level 1 = 0 EXP
 * Level L = floor(100 * (L - 1)^1.5)
 */
export function getExpForLevel(level: number): number {
  if (level <= 1) return 0;
  return Math.floor(100 * Math.pow(level - 1, 1.5));
}

export function getLevelFromExp(exp: number): number {
  if (exp <= 0) return 1;
  // exp = 100 * (level - 1)^1.5  =>  level = (exp / 100)^(2/3) + 1
  const calculatedLevel = Math.floor(Math.pow(exp / 100, 2 / 3)) + 1;
  return Math.max(1, calculatedLevel);
}

export function getExpProgressInCurrentLevel(exp: number): {
  currentLevel: number;
  currentLevelExp: number;
  nextLevelExp: number;
  expInLevel: number;
  neededInLevel: number;
  percent: number;
} {
  const currentLevel = getLevelFromExp(exp);
  const currentLevelBaseExp = getExpForLevel(currentLevel);
  const nextLevelBaseExp = getExpForLevel(currentLevel + 1);

  const expInLevel = Math.max(0, exp - currentLevelBaseExp);
  const neededInLevel = Math.max(1, nextLevelBaseExp - currentLevelBaseExp);
  const percent = Math.min(100, Math.round((expInLevel / neededInLevel) * 100));

  return {
    currentLevel,
    currentLevelExp: currentLevelBaseExp,
    nextLevelExp: nextLevelBaseExp,
    expInLevel,
    neededInLevel,
    percent,
  };
}

