export function getTodayDateString(): string {
  const now = new Date();
  return now.toISOString().split('T')[0]; // YYYY-MM-DD
}

/**
 * Returns deterministic 3 daily quests for a given YYYY-MM-DD date string
 */
export function getQuestsForDate(dateStr: string): DailyQuestDef[] {
  let hash = 0;
  for (let i = 0; i < dateStr.length; i++) {
    hash = (hash << 5) - hash + dateStr.charCodeAt(i);
    hash |= 0;
  }
  const positiveHash = Math.abs(hash);

  const quest1 = DAILY_QUEST_POOL[positiveHash % 2]; // either read 1 or 2
  const quest2 = DAILY_QUEST_POOL[2 + (positiveHash % 2)]; // quiz 3 or 6
  const quest3 = DAILY_QUEST_POOL[4 + (positiveHash % 2)]; // dsa or arcade

  return [quest1, quest2, quest3];
}
