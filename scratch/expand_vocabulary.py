def format_term(term):
    lines = []
    lines.append("  {")
    lines.append(f"    id: '{term['id']}',")
    lines.append(f"    term: '{term['term']}',")
    lines.append(f"    phonetic: '{term['phonetic']}',")
    lines.append(f"    pos: '{term['pos']}',")
    lines.append(f"    category: '{term['category']}',")
    lines.append(f"    categoryLabel: '{term['categoryLabel']}',")
    lines.append(f"    vnMeaning: '{term['vnMeaning']}',")
    
    # Escape quotes
    vn_def = term['vnDefinition'].replace("'", "\\'")
    lines.append(f"    vnDefinition: '{vn_def}',")
    
    analogy = term['analogy'].replace("'", "\\'")
    lines.append(f"    analogy: '{analogy}',")
    
    if 'codeExample' in term and term['codeExample']:
        code = term['codeExample'].replace("\\", "\\\\").replace("'", "\\'").replace("\n", "\\n")
        lines.append(f"    codeExample: '{code}',")
        
    collocs = ", ".join(f"'{c}'" for c in term['collocations'])
    lines.append(f"    collocations: [{collocs}],")
    
    tip = term['interviewTip'].replace("'", "\\'")
    lines.append(f"    interviewTip: '{tip}',")
    lines.append("  },")
    return "\n".join(lines)

def run():
    with open('src/data/techEnglishVocabularyData.ts', 'r', encoding='utf-8') as f:
        content = f.read()

    # Find existing IDs to avoid duplicates
    existing_ids = set(re.findall(r"id:\s*'([^']+)'", content))
    print(f"Existing term count: {len(existing_ids)}")

    # Category markers in file
    cat_markers = {
        'system-design': '// 2. DATABASES & STORAGE ENGINES',
        'database': '// 3. OS & LOW-LEVEL CONCURRENCY',
        'os-concurrency': '// 4. NETWORKING & WEB PROTOCOLS',
        'networking': '// 5. JAVA & JVM RUNTIME',
        'java-jvm': '// 6. SECURITY & AUTHENTICATION',
        'security': '// 7. DEVOPS, CLOUD & SRE',
        'devops': '];\n'
    }

    added_total = 0
    for cat, terms in NEW_TERMS_BY_CATEGORY.items():
        new_terms = [t for t in terms if t['id'] not in existing_ids]
        if not new_terms:
            continue
        
        formatted_chunk = "\n" + "\n".join(format_term(t) for t in new_terms) + "\n"
        marker = cat_markers[cat]
        
        idx = content.find(marker)
        if idx == -1:
            print(f"Error: marker not found for {cat}: {marker}")
            return
            
        if cat == 'devops':
            insert_idx = idx
        else:
            sep_idx = content.rfind('// ==========================================', 0, idx)
            insert_idx = sep_idx if sep_idx != -1 else idx
            
        content = content[:insert_idx] + formatted_chunk + content[insert_idx:]
        added_total += len(new_terms)
        print(f"Added {len(new_terms)} terms to {cat}")

    with open('src/data/techEnglishVocabularyData.ts', 'w', encoding='utf-8') as f:
        f.write(content)

    print(f"Successfully added {added_total} terms. File updated!")

if __name__ == '__main__':
    run()
